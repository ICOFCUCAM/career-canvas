// Shared template definitions with CV preview style mappings

export interface TemplateStyle {
  // Layout
  layout: "two-column" | "single-column" | "sidebar-left" | "sidebar-right" | "top-header";
  // Colors (CSS values)
  primaryColor: string;
  accentColor: string;
  headerBg: string;
  headerText: string;
  bodyBg: string;
  bodyText: string;
  sectionTitleColor: string;
  skillBadgeBg: string;
  skillBadgeText: string;
  // Typography
  nameSize: string;
  titleFont: string;
  bodyFont: string;
  sectionStyle: "uppercase-tracking" | "bold-underline" | "accent-border" | "icon-prefix" | "minimal-dot";
  // Spacing & decoration
  borderRadius: string;
  sectionDivider: "line" | "dots" | "none" | "gradient" | "thick-accent";
  avatarShape: "circle" | "rounded" | "square" | "none";
}

export interface TemplateDefinition {
  id: string;
  name: string;
  category: string;
  description: string;
  imageKey: string; // maps to imported image
  style: TemplateStyle;
  sampleData?: {
    name?: string;
    title?: string;
    summary?: string;
  };
}

